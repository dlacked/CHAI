"""
Re-derives every access.tex number that depends on the Z. Ghorbani et al. reproduction's
classifier, after retraining it with the RandomResizedCrop augmentation fix
(comparison/ghorbani/train_classify_fast.py). K. Yoon et al.'s numbers are untouched (that model
was not retrained), so this script only recomputes the proposed-model-vs-Ghorbani half of each
comparison; CHAI-vs-Yoon numbers already in the paper stay valid as-is.

Loads:
  - ResNet/results/chai_raw_vs_hungarian_per_jaw.pkl ["hungarian"] - the proposed
    model's full-test-set predictions (same pipeline used for Table 1/2's "Proposed (Ours)" row).
  - comparison/ghorbani/results/ghorbani_per_jaw.pkl - freshly regenerated by
    evaluate_table_restructure.py against the retrained classify_best.pth.

Recomputes, matching Table 1/2's exact bucketing logic (functions/eval_metrics.py):
  - Missing-tooth subset (>=1 missing tooth): per-arch Exact-Match Accuracy for Ghorbani (new),
    plus a paired McNemar exact test (proposed vs Ghorbani) on this subset.
  - Class II+III merged subset: same, merged into ONE per-arch accuracy number (Table 2's
    "Accuracy (n=5,224)" column merges Class II and Class III into a single population - the
    per-class-only compute_arch_metrics_by_complexity does not do this merge itself, so it's done
    here directly from arch_exact), plus a paired McNemar exact test.
  - Full test set (n=7,152): Ghorbani's own Exact-Match Accuracy, needed for any full-test-set
    sentence that cites it directly.

Usage:
    .venv/Scripts/python.exe comparison/ghorbani/recompute_paper_numbers.py
"""
import importlib.util
import json
import pickle
import sys
from pathlib import Path

from scipy.stats import binomtest

GHORBANI_DIR = Path(__file__).resolve().parent
_bootstrap_root = GHORBANI_DIR.parent.parent
if str(_bootstrap_root) not in sys.path:
    sys.path.append(str(_bootstrap_root))
from config import PathConfig
PROJECT_ROOT = PathConfig.ROOT
CHAI_PKL = PROJECT_ROOT / "ResNet" / "results" / "chai_raw_vs_hungarian_per_jaw.pkl"
GHORBANI_PKL = GHORBANI_DIR / "results" / "ghorbani_per_jaw.pkl"
YOON_PKL = PROJECT_ROOT / "comparison" / "yoon" / "results" / "yoon_per_jaw.pkl"
DATASET_DIR = PROJECT_ROOT.parent / "dataset"


def load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, str(path))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


tooth_module = load_module("chai_tooth_graph_recompute", PROJECT_ROOT / "functions" / "eval_metrics.py")
complexity_build = load_module(
    "vit_complexity_build_recompute", PROJECT_ROOT / "functions" / "features" / "complexity_labels.py")


def build_arch_exact(per_jaw, pred_key="y_pred", tens_pred_key="y_tens_pred"):
    """Per-arch exact-match boolean, keyed (jaw, image_name) - same is_correct definition
    tooth.py's compute_missing_vs_complete_metrics / compute_arch_metrics_by_complexity use."""
    arch_exact = {}
    for jaw in ("lower", "upper"):
        d = per_jaw[jaw]
        for pred_digit, true_digit, tens_pred, fdi_number, image_name in zip(
                d[pred_key], d["y_true"], d[tens_pred_key], d["y_fdi_number"], d["y_image_name"]):
            arch_key = (jaw, image_name)
            is_correct = pred_digit == true_digit and tens_pred == (fdi_number // 10)
            arch_exact[arch_key] = arch_exact.get(arch_key, True) and is_correct
    return arch_exact


def build_arch_position_sets(per_jaw, pred_key="y_pred", tens_pred_key="y_tens_pred"):
    """Per-arch (true FDI-number set, predicted FDI-number set), keyed (jaw, image_name) - same
    12-slot-per-arch position representation as Supplementary Table S5 ("Missing-Tooth Recognition
    in Each Model's Final Output"): the predicted set is each model's own FINAL post-processed
    output (Hungarian for the proposed model, Ghorbani's own duplicate-resolution step for
    Ghorbani), not the raw per-tooth argmax."""
    arch_true, arch_pred = {}, {}
    for jaw in ("lower", "upper"):
        d = per_jaw[jaw]
        for pred_digit, tens_pred, fdi_number, image_name in zip(
                d[pred_key], d[tens_pred_key], d["y_fdi_number"], d["y_image_name"]):
            arch_key = (jaw, image_name)
            arch_true.setdefault(arch_key, set()).add(fdi_number)
            arch_pred.setdefault(arch_key, set()).add(tens_pred * 10 + (pred_digit + 1))
    return arch_true, arch_pred


def missing_tooth_recognition_metrics(arch_true, arch_pred, keys, full_arch_size=12):
    """Table S5's pooled (not per-arch-averaged) Precision/Recall/F1/Slot Accuracy/Arch Exact
    Match over each arch's 12 canonical FDI-position slots, treated as a binary presence/absence
    label - matches access_supplementary.tex's S5 description exactly."""
    tp = fp = fn = 0
    exact_matches = 0
    for k in keys:
        true_set, pred_set = arch_true[k], arch_pred[k]
        tp += len(true_set & pred_set)
        fp += len(pred_set - true_set)
        fn += len(true_set - pred_set)
        if true_set == pred_set:
            exact_matches += 1
    n_arches = len(keys)
    total_slots = n_arches * full_arch_size
    tn = total_slots - tp - fp - fn
    precision = tp / (tp + fp) if (tp + fp) else float("nan")
    recall = tp / (tp + fn) if (tp + fn) else float("nan")
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else float("nan")
    slot_accuracy = (tp + tn) / total_slots
    arch_exact_match = exact_matches / n_arches
    return {"precision": precision, "recall": recall, "f1": f1,
            "slot_accuracy": slot_accuracy, "arch_exact_match": arch_exact_match,
            "n_arches": n_arches, "n_slots": total_slots}


def mcnemar(exact_a, exact_b, keys, label_a="A", label_b="B"):
    """Exact (binomial) McNemar test on discordant pairs, matching scipy's mcnemar exact-test
    convention (binomtest on the discordant counts, two-sided)."""
    a_only = sum(1 for k in keys if exact_a[k] and not exact_b[k])
    b_only = sum(1 for k in keys if exact_b[k] and not exact_a[k])
    n_discordant = a_only + b_only
    if n_discordant == 0:
        p = 1.0
    else:
        p = binomtest(min(a_only, b_only), n_discordant, 0.5, alternative="two-sided").pvalue
    print(f"  McNemar {label_a} vs {label_b}: {a_only} vs {b_only} discordant arches "
          f"(favoring {label_a}), p={p:.3g}")
    return {"a_only": a_only, "b_only": b_only, "p": p}


def main():
    with open(CHAI_PKL, "rb") as f:
        chai_hungarian = pickle.load(f)["hungarian"]
    with open(GHORBANI_PKL, "rb") as f:
        ghorbani = pickle.load(f)

    complexity_by_image = complexity_build.load_complexity_labels(DATASET_DIR, "test")

    chai_exact = build_arch_exact(chai_hungarian)
    ghorbani_exact = build_arch_exact(ghorbani)

    common_keys = set(chai_exact) & set(ghorbani_exact)
    print(f"Common arch keys (proposed model & Ghorbani): {len(common_keys)}")
    missing_only_chai = set(chai_exact) - set(ghorbani_exact)
    missing_only_ghorbani = set(ghorbani_exact) - set(chai_exact)
    if missing_only_chai or missing_only_ghorbani:
        print(f"  WARNING: {len(missing_only_chai)} keys only in CHAI, "
              f"{len(missing_only_ghorbani)} only in Ghorbani - check test-set alignment.")

    # --- Full test set ---
    print("\n=== Full test set ===")
    n_full = len(common_keys)
    chai_full_acc = sum(chai_exact[k] for k in common_keys) / n_full
    ghorbani_full_acc = sum(ghorbani_exact[k] for k in common_keys) / n_full
    print(f"Proposed (Ours): {chai_full_acc:.4f} (n={n_full})")
    print(f"Ghorbani (new):  {ghorbani_full_acc:.4f} (n={n_full})")
    mcnemar_full = mcnemar(chai_exact, ghorbani_exact, common_keys, "Proposed", "Ghorbani")

    # --- Missing-tooth subset (>=1 missing) ---
    print("\n=== Missing-tooth subset ===")
    missing_buckets = tooth_module.build_missing_count_buckets(ghorbani)
    missing_keys = {k for k, cnt in missing_buckets.items() if cnt >= 1 and k in common_keys}
    n_missing = len(missing_keys)
    chai_missing_acc = sum(chai_exact[k] for k in missing_keys) / n_missing
    ghorbani_missing_acc = sum(ghorbani_exact[k] for k in missing_keys) / n_missing
    print(f"n_arches={n_missing}")
    print(f"Proposed (Ours): {chai_missing_acc:.4f}")
    print(f"Ghorbani (new):  {ghorbani_missing_acc:.4f}")
    mcnemar_missing = mcnemar(chai_exact, ghorbani_exact, missing_keys, "Proposed", "Ghorbani")
    print(f"Error rate ratio (Ghorbani/Proposed): "
          f"{(1 - ghorbani_missing_acc) / (1 - chai_missing_acc):.1f}x")

    # --- Class II+III merged subset ---
    print("\n=== Class II+III merged subset ===")
    class23_keys = {k for k in common_keys
                     if complexity_by_image.get(k[1]) in (2, 3)}
    n_class23 = len(class23_keys)
    chai_class23_acc = sum(chai_exact[k] for k in class23_keys) / n_class23
    ghorbani_class23_acc = sum(ghorbani_exact[k] for k in class23_keys) / n_class23
    print(f"n_arches={n_class23}")
    print(f"Proposed (Ours): {chai_class23_acc:.4f}")
    print(f"Ghorbani (new):  {ghorbani_class23_acc:.4f}")
    mcnemar_class23 = mcnemar(chai_exact, ghorbani_exact, class23_keys, "Proposed", "Ghorbani")

    # --- Supplementary Table S5: missing-tooth recognition in each model's final output ---
    print("\n=== Table S5 (missing-tooth subset, final-output position recognition) ===")
    chai_true, chai_pred = build_arch_position_sets(chai_hungarian)
    ghorbani_true, ghorbani_pred = build_arch_position_sets(ghorbani)
    s5_chai = missing_tooth_recognition_metrics(chai_true, chai_pred, missing_keys)
    s5_ghorbani = missing_tooth_recognition_metrics(ghorbani_true, ghorbani_pred, missing_keys)
    print(f"Proposed (Ours): {s5_chai}")
    print(f"Ghorbani (new):  {s5_ghorbani}")

    s5_yoon = None
    if YOON_PKL.exists():
        with open(YOON_PKL, "rb") as f:
            yoon = pickle.load(f)
        yoon_true, yoon_pred = build_arch_position_sets(yoon)
        yoon_missing_keys = {k for k in missing_keys if k in yoon_true}
        s5_yoon = missing_tooth_recognition_metrics(yoon_true, yoon_pred, yoon_missing_keys)
        print(f"Yoon (recomputed, same methodology): {s5_yoon}")

    out = {
        "full": {"n": n_full, "proposed_acc": chai_full_acc, "ghorbani_acc": ghorbani_full_acc,
                 "mcnemar": mcnemar_full},
        "missing": {"n": n_missing, "proposed_acc": chai_missing_acc,
                    "ghorbani_acc": ghorbani_missing_acc, "mcnemar": mcnemar_missing},
        "class23": {"n": n_class23, "proposed_acc": chai_class23_acc,
                    "ghorbani_acc": ghorbani_class23_acc, "mcnemar": mcnemar_class23},
        "s5_missing_tooth_recognition": {"proposed": s5_chai, "ghorbani": s5_ghorbani, "yoon": s5_yoon},
    }
    out_path = GHORBANI_DIR / "results" / "ghorbani_paper_numbers_recomputed.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2)
    print(f"\nSaved to {out_path}")


if __name__ == "__main__":
    main()
